#!/usr/bin/env python3
"""m68kops_hot.txt (handler names, hottest first; from tools/prof/ops.py --list)
-> m68kops_layout.h: one section per handler, named so that the linker script's
SORT(.text.m68k.*) lays them out contiguously in that order."""
import sys
names = [l.strip() for l in open(sys.argv[1]) if l.strip() and not l.startswith(('#', '0x'))]
with open(sys.argv[2], 'w') as f:
    f.write("/* Generated by tools/prof/mklayout.py from m68kops_hot.txt: do not edit. */\n")
    # M68K_HOT_FIRST=N: handlers after the first N get sections from 1000 up,
    # leaving 0100+N..0999 for other code (e.g. HLE_SECTION_BASE=500 puts the
    # AOT functions between the hottest handlers and the rest)
    import os
    first = int(os.environ.get('M68K_HOT_FIRST', '100000'))
    for i, n in enumerate(names):
        f.write(f'static void {n}(void) __attribute__((section(".text.m68k.{i + (100 if i < first else 1000):04d}")));\n')
